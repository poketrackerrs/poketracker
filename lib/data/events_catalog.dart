// A cross-generation reference catalog of notable event / distribution Pokémon.
// Data-only for now (browsable in-app); Gen 3 also has an injectable build in
// gen3_events.dart. Injection for other gens will hook into this as each
// generation's save codec is added.

class EventMon {
  final int gen;
  final String name; // display, e.g. "Manaphy (TRU)"
  final int dex; // national dex number
  final String games; // short display, e.g. "D/P/Pt · HG/SS"
  final int level;
  final String ot; // original trainer / distribution name ('' if unknown)
  final String note; // method + moves/held-item summary
  const EventMon({
    required this.gen,
    required this.name,
    required this.dex,
    required this.games,
    required this.level,
    this.ot = '',
    this.note = '',
  });
}

