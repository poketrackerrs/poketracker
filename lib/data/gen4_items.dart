String gen4ItemName(int id) => kGen4Items[id] ?? 'Item #$id';

/// Which pocket a Gen 4 item id belongs to (DP/Pt routing; HGSS Apricorn balls
/// 492–500 also route to Balls). Returns null for ids that aren't valid bag
/// items. Mirrors PKHeX's per-pouch legal-item lists as clean ranges.
Gen4Pocket? gen4PocketOf(int id) {
  if (id <= 0) return null;
  if ((id >= 1 && id <= 16 && id != 5) || (id >= 492 && id <= 500)) {
    return Gen4Pocket.balls;
  }
  if (id >= 17 && id <= 54) return Gen4Pocket.medicine;
  if (id >= 55 && id <= 67) return Gen4Pocket.battle;
  if (id >= 137 && id <= 148) return Gen4Pocket.mail;
  if (id >= 149 && id <= 212) return Gen4Pocket.berries;
  if (id >= 328 && id <= 427) return Gen4Pocket.tmHm; // TM01–92, HM01–08
  if ((id >= 68 && id <= 112) || id == 134 || id == 135 || id == 136 ||
      (id >= 213 && id <= 327)) {
    return Gen4Pocket.items;
  }
  if (id >= 428 && id <= 536) return Gen4Pocket.keyItems;
  return null;
}

/// Items selectable in the picker for a given pocket (id + name), sorted by id.
List<({int id, String name})> gen4ItemsInPocket(Gen4Pocket pocket) {
  final out = <({int id, String name})>[];
  for (final e in kGen4Items.entries) {
    if (e.key == 0) continue;
    if (gen4PocketOf(e.key) == pocket) out.add((id: e.key, name: e.value));
  }
  out.sort((a, b) => a.id.compareTo(b.id));
  return out;
}
